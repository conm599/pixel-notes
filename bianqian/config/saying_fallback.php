if (!function_exists('sayingFallbackJson')) {

    /**
     * 从本地兜底库随机取一条，返回与上游一致的 JSON 字符串
     */
    function sayingFallbackJson()
    {
        $list = sayingFallbackList();
        $n = count($list);
        if ($n < 1) {
            return json_encode(array('text' => '心之所愿，无所不成。'), JSON_UNESCAPED_UNICODE);
        }
        try {
            $idx = random_int(0, $n - 1);
        } catch (Throwable $e) {
            $idx = mt_rand(0, $n - 1);
        }
        return json_encode(array('text' => $list[$idx]), JSON_UNESCAPED_UNICODE);
    }
}

if (!function_exists('sayingFallbackLog')) {

    /**
     * 记录一次兜底触发（便于判断上游质量）。
     * 日志落在 data/（nginx 已 deny），超过 512KB 自动轮转一次。
     */
    function sayingFallbackLog($code = 0, $resp = '')
    {
        $dir = dirname(__DIR__) . '/data';
        if (!is_dir($dir)) {
            @mkdir($dir, 0755, true);
        }
        $file = $dir . '/saying_fallback.log';
        if (is_file($file) && @filesize($file) > 524288) {
            @rename($file, $file . '.1');
        }
        $snip = '';
        if (is_string($resp) && $resp !== '') {
            $snip = preg_replace('/\s+/', ' ', $resp);
            $snip = function_exists('mb_substr') ? mb_substr($snip, 0, 120, 'UTF-8') : substr($snip, 0, 120);
        }
        $line = sprintf("[%s] http=%d %s\n", date('Y-m-d H:i:s'), (int)$code, $snip);
        @file_put_contents($file, $line, FILE_APPEND | LOCK_EX);
    }
}
